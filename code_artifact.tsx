// 6. 相性計算エンジン（共鳴度 × 補完度）
// ==========================================
function calculateCompatibility(userStats, selectedTags, char) {
  const keys = ['action', 'empathy', 'logic', 'passion', 'justice', 'flexibility'];
  const uVec = keys.map(k => userStats[k]);
  const cVec = char.stats;

  // 1. 共鳴度 (Resonance): 波形パターンの近さ + 絶対値の近さ
  let diffSum = 0;
  for (let i = 0; i < 6; i++) {
    diffSum += Math.abs(uVec[i] - cVec[i]);
  }
  const avgDiff = diffSum / 6; // 0〜50程度
  const baseResonance = Math.max(45, Math.min(99, Math.round(100 - avgDiff * 1.15)));

  // タグ一致ボーナス
  const matchedTags = char.tags.filter(t => selectedTags.includes(t));
  const tagBonus = matchedTags.length * 3.5;

  const resonanceScore = Math.min(99, Math.round(baseResonance + tagBonus));

  // 2. 憧れ・補完度 (Synergy): ユーザーの弱점을キャラが高数値でカバーし、キャラの弱点をユーザーがカバーする度合い
  let synergyPoints = 0;
  let bestComplementAxis = null;
  let maxComplementGap = -999;

  for (let i = 0; i < 6; i++) {
    // キャラがユーザーより高い部分（憧れ・引っ張ってくれる力）
    const charLead = Math.max(0, cVec[i] - uVec[i]);
    // ユーザーがキャラより高い部分（支えてあげられる力）
    const userLead = Math.max(0, uVec[i] - cVec[i]);
    // 両方とも高い部分（倍増シナジー）
    const bothHigh = (uVec[i] >= 80 && cVec[i] >= 80) ? 14 : 0;

    synergyPoints += (charLead * 0.45) + (userLead * 0.35) + bothHigh;

    if (cVec[i] - uVec[i] > maxComplementGap) {
      maxComplementGap = cVec[i] - uVec[i];
      bestComplementAxis = AXES[i];
    }
  }

  const synergyScore = Math.min(99, Math.max(68, Math.round(62 + synergyPoints * 0.65 + matchedTags.length * 2)));

  // 総合シンクロ率
  const totalScore = Math.min(99, Math.round(resonanceScore * 0.58 + synergyScore * 0.42));

  // 最も共鳴している軸（両者とも高く、差が小さい軸）
  let bestResonanceAxis = AXES[0];
  let bestResVal = -999;
  for (let i = 0; i < 6; i++) {
    const score = (uVec[i] + cVec[i]) / 2 - Math.abs(uVec[i] - cVec[i]) * 0.8;
    if (score > bestResVal) {
      bestResVal = score;
      bestResonanceAxis = AXES[i];
    }
  }

  return {
    char,
    totalScore,
    resonanceScore,
    synergyScore,
    matchedTags,
    bestResonanceAxis,
    bestComplementAxis,
  };
}

